#!/usr/bin/env node
import assert from 'node:assert/strict';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(await readFile(path.join(root, 'themes/design-tokens.json'), 'utf8'));
const check = process.argv.includes('--check');

async function output(relative, content) {
    const filename = path.join(root, relative);
    content = `${content.trim()}\n`;
    if (check) {
        assert.equal(await readFile(filename, 'utf8'), content, `${relative} is not generated from design tokens`);
        return;
    }
    await mkdir(path.dirname(filename), {recursive: true});
    await writeFile(filename, content);
}

